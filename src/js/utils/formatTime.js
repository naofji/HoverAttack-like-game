// ============================================
// 経過時間の表示整形
// ============================================

/**
 * ミリ秒を "MM:SS.XX"（分:秒.1/100秒）にする。
 *
 * クリアタイムはミッションクリア画面・ゲームクリア画面・ランキング登録・
 * 面別ランキングの4箇所に出るが、以前はそれぞれが同じ式を書き写していた
 * （うち2つは「分」を ms/60000 から、残りは秒に直してから求めていて、
 * 式の形だけが違う同じ計算だった）。書式を変えたいときに直し漏れるので、
 * 唯一の整形箇所にまとめる。
 *
 * 分は 60 で折り返さない（99分を超える想定が無いため 2 桁ゼロ詰め）。
 *
 * @param {number} ms 経過ミリ秒
 * @returns {string} "MM:SS.XX"
 */
export function formatClock(ms) {
    const mm = Math.floor(ms / 60000);
    const ss = Math.floor((ms % 60000) / 1000);
    const xx = Math.floor((ms % 1000) / 10);
    return `${String(mm).padStart(2, '0')}:${String(ss).padStart(2, '0')}.${String(xx).padStart(2, '0')}`;
}
