// ============================================
// waterRules - 水のシミュレーション・分類・描画が共有する規則（純関数）
// ============================================
//
// 「下のマスが水を支えるか」は、落下・横の流れの落ち口・休眠・水圧の通り道・
// 種別（滝か）・滝の描画が全部読む。以前は6か所に別々の式で書かれていて、
// 別ブランチで片方だけ条件を足してずれを出したことがある（waterQuery.js の
// classifyWaterColumn のコメント）。定義をここ1つにして全員に読ませる。

import { MAX_WATER_MASS } from '../utils/Constants.js';

/**
 * (r, c) がその上の水を支えるか: マップの底より下・岩・満水のどれか。
 * 支えないマスの上の水は落ちられる（フェーズ1が落とし、フェーズ2はそこを落ち口とみなす）。
 *
 * 底を先に見るのは、テストの isSolid に範囲外を扱わないものがあるのと、
 * 呼び出し側が r + 1 をそのまま渡せるようにするため。
 */
export function supportsWater(water, rows, cols, isSolid, r, c) {
    return r >= rows || isSolid(r, c) || water[r * cols + c] >= MAX_WATER_MASS;
}
